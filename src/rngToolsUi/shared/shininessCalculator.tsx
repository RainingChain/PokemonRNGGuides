import React from "react";
import {
  Flex,
  FormFieldTable,
  NumberInput,
  Typography,
  Field,
  TooltipWithIcon,
} from "~/components";

const MAX_U16 = 0xffff;
const MAX_U32 = 0xffffffff;

const clamp = (value: number | null, max: number) => {
  if (value == null || value < 0) {
    return 0;
  }

  return Math.min(value, max);
};

const pidHigh = (pid: number) => (pid >>> 16) & MAX_U16;
const pidLow = (pid: number) => pid & MAX_U16;
const shinyValue = (tid: number, sid: number, pid: number) =>
  (tid ^ sid ^ pidHigh(pid) ^ pidLow(pid)) & MAX_U16;
const tsv = (tid: number, sid: number) => (tid ^ sid) >>> 3;
const psv = (pid: number) => (pidHigh(pid) ^ pidLow(pid)) >>> 3;
const findSquareShinySid = (tid: number, pid: number) =>
  (tid ^ pidHigh(pid) ^ pidLow(pid)) & MAX_U16;

const formatId = (value: number) => value.toString();

const OutputValue = ({ children }: { children: React.ReactNode }) => (
  <Typography.Text strong>{children}</Typography.Text>
);

export const FindSidForShinyPokemon = () => {
  const [tid, setTid] = React.useState(0);
  const [pid, setPid] = React.useState(0);

  const sid = findSquareShinySid(tid, pid);
  const starSids = Array.from({ length: 7 }, (_, index) => sid ^ (index + 1)).sort(
    (a, b) => a - b,
  );
  const targetTsv = tsv(tid, sid);
  const targetPsv = psv(pid);

  const fields: Field[] = [
    {
      key: "TID",
      label: (
        <TooltipWithIcon title="Trainer ID: the ID shown on your Trainer Card. Together with your Secret ID, it determines which Pokémon are shiny for you.">
          TID
        </TooltipWithIcon>
      ),
      input: (
        <NumberInput
          numType="decimal"
          value={tid}
          onChange={(value) => setTid(clamp(value, MAX_U16))}
        />
      ),
    },
    {
      key: "PID",
      label: (
        <TooltipWithIcon title="Personality ID: a hidden Pokémon ID generated by the game the moment a Pokémon is created.">
          PID
        </TooltipWithIcon>
      ),
      input: (
        <NumberInput
          numType="hex"
          value={pid}
          onChange={(value) => setPid(clamp(value, MAX_U32))}
        />
      ),
    },
    {
      key: "PSV",
      label: (
        <TooltipWithIcon title="Pokémon Shiny Value: a number calculated from a Pokémon's PID (personality value). In this calculator, it must match your TSV for the Pokémon to be shiny.">
          PSV
        </TooltipWithIcon>
      ),
      input: <OutputValue>{formatId(targetPsv)}</OutputValue>,
    },
    {
      key: "SID",
      label: (
        <TooltipWithIcon title="Secret ID: a hidden trainer ID generated when you start your game. It works with your Trainer ID to determine shininess.">
          SID
        </TooltipWithIcon>
      ),
      input: (
        <Flex vertical gap={4}>
          <OutputValue>Shiny (Square in Gen 8+): {formatId(sid)}.</OutputValue>
          <OutputValue>Shiny (Star in Gen 8+): {starSids.map(formatId).join(", ")}.</OutputValue>
        </Flex>
      ),
    },
    {
      key: "TSV",
      label: (
        <TooltipWithIcon title="Trainer Shiny Value: a number calculated from your TID and SID. In this calculator, a Pokémon is shiny when its PSV matches your TSV.">
          TSV
        </TooltipWithIcon>
      ),
      input: <OutputValue>{formatId(targetTsv)}</OutputValue>,
    },
  ];

  return (
      <FormFieldTable fields={fields} />
  );
};

const getShininess = (value: number) => {
  if (value === 0) {
    return "Shiny (Square in Gen 8+)";
  }

  if (value < 8) {
    return "Shiny (Star in Gen 8+)";
  }

  return "No";
};

