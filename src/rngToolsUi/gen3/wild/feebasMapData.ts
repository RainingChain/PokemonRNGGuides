const WIDTH = tiles[0].length;
const SECTION_HEIGHTS = [45, 91];
const CYCLE_PER_CHECK = 413;

export type FeebasTile = {
  websiteImageY: number;
  websiteImageX: number;
  ingameY: number;
  ingameX: number;
  canContainFeebas: boolean;
  cycleCounter: number;
  section: number;
  yInSection: number;
  instability: number;
  tileNoInSection: number;
};

const getInstability = (cycleCounter: number) => {
  const isStable =
    (cycleCounter >= 0 && cycleCounter <= 205_895) ||
    (cycleCounter >= 235_896 && cycleCounter <= 421_791) ||
    (cycleCounter >= 471_792 && cycleCounter <= 637_687) ||
    (cycleCounter >= 707_688 && cycleCounter <= 800_000);

  // TODO: Improve formula to return values between 0 and 1.
  return isStable ? 0 : 1;
};

export const getFeebasTiles = (): FeebasTile[] => {
  return tiles
    .map((row, websiteImageY) => {
      return row.split("").map((val, websiteImageX) => {
        const ingameX = websiteImageX;
        const ingameY = 16 + websiteImageY;
        const [section, yInSection] = match(ingameY)
          .when(
            (y) => y <= SECTION_HEIGHTS[0],
            (y) => [0, y],
          )
          .when(
            (y) => y <= SECTION_HEIGHTS[1],
            (y) => [1, y - SECTION_HEIGHTS[0]],
          )
          .otherwise((y) => [2, y - SECTION_HEIGHTS[1]]);

        const tileNoInSection = yInSection * WIDTH + ingameX;
        const cycleCounter = tileNoInSection * CYCLE_PER_CHECK + section;

        return {
          websiteImageY,
          websiteImageX,
          ingameY,
          ingameX,
          canContainFeebas: val === "1",
          cycleCounter: cycleCounter,
          instability: getInstability(cycleCounter),
          section,
          yInSection,
          tileNoInSection,
        };
      });
    })
    .flat();
};
